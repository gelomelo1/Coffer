-- Coffer marketplace migration (2026-11-13)
-- Replaces the old barter tables (trades/offers/trade_reviews) with the marketplace schema.
-- Old barter data is intentionally dropped (confirmed: no trading data needs to be kept).
-- Generated from the EF model (CofferDbContext + MarketplaceModel) plus enum CHECK constraints.
-- Run with:  docker compose -f docker-compose.dev.yml exec -T db psql -U postgres -d Coffer < startup/marketplace_migration.sql

BEGIN;

DROP TABLE IF EXISTS offer_items, offers, trade_items, trade_reviews, trades,
    trade_images, trade_followers, trade_chat_messages, trade_chats, trade_confirmations, reports CASCADE;

DROP TABLE IF EXISTS moderation_cases, reviews, deals, messages, conversation_participants, conversations,
    listing_images, listing_lines, listings, cities CASCADE;

CREATE TABLE cities (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    external_id bigint NOT NULL,
    name text NOT NULL,
    admin1 text,
    country_code text NOT NULL,
    latitude double precision NOT NULL,
    longitude double precision NOT NULL,
    CONSTRAINT pk_cities PRIMARY KEY (id)
);
CREATE TABLE conversations (
    id uuid NOT NULL,
    subject_type text NOT NULL,
    subject_id uuid NOT NULL,
    created_at timestamp with time zone NOT NULL,
    last_message_at timestamp with time zone NOT NULL,
    owner_first_response_at timestamp with time zone,
    agreed_price_cents integer,
    CONSTRAINT pk_conversations PRIMARY KEY (id)
);
CREATE TABLE conversation_participants (
    conversation_id uuid NOT NULL,
    user_id uuid NOT NULL,
    role character varying(40) NOT NULL,
    last_read_at timestamp with time zone,
    joined_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_conversation_participants PRIMARY KEY (conversation_id, user_id),
    CONSTRAINT fk_conversation_participants_conversations_conversation_id FOREIGN KEY (conversation_id) REFERENCES conversations (id) ON DELETE CASCADE,
    CONSTRAINT fk_conversation_participants_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE TABLE listings (
    id uuid NOT NULL,
    owner_id uuid NOT NULL,
    kind character varying(40) NOT NULL,
    collection_type_id integer NOT NULL,
    title text NOT NULL,
    description text,
    price_cents integer,
    currency text NOT NULL DEFAULT 'EUR',
    exchange_for text,
    condition character varying(40),
    city_id integer NOT NULL,
    allows_local_pickup boolean NOT NULL,
    allows_shipping boolean NOT NULL,
    status character varying(40) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_listings PRIMARY KEY (id),
    CONSTRAINT ck_listings_delivery CHECK (allows_local_pickup OR allows_shipping),
    CONSTRAINT fk_listings_cities_city_id FOREIGN KEY (city_id) REFERENCES cities (id) ON DELETE RESTRICT,
    CONSTRAINT fk_listings_collection_types_collection_type_id FOREIGN KEY (collection_type_id) REFERENCES collection_types (id) ON DELETE RESTRICT,
    CONSTRAINT fk_listings_users_owner_id FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE TABLE messages (
    id uuid NOT NULL,
    conversation_id uuid NOT NULL,
    sender_id uuid,
    kind character varying(40) NOT NULL,
    body text NOT NULL,
    payload jsonb,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_messages PRIMARY KEY (id),
    CONSTRAINT fk_messages_conversations_conversation_id FOREIGN KEY (conversation_id) REFERENCES conversations (id) ON DELETE CASCADE,
    CONSTRAINT fk_messages_users_sender_id FOREIGN KEY (sender_id) REFERENCES users (id) ON DELETE SET NULL
);
CREATE TABLE deals (
    id uuid NOT NULL,
    listing_id uuid NOT NULL,
    conversation_id uuid NOT NULL,
    seller_id uuid NOT NULL,
    buyer_id uuid NOT NULL,
    method character varying(40) NOT NULL,
    status character varying(40) NOT NULL,
    agreed_price_cents integer,
    meetup_at timestamp with time zone,
    meetup_place text,
    handoff_pin character varying(4),
    pin_failed_attempts integer NOT NULL,
    pin_locked_until timestamp with time zone,
    carrier text,
    tracking_number text,
    shipment_photo text,
    shipped_at timestamp with time zone,
    receipt_photo text,
    received_at timestamp with time zone,
    completed_at timestamp with time zone,
    completion_reason character varying(40),
    review_deadline timestamp with time zone,
    cancelled_by uuid,
    cancel_reason text,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_deals PRIMARY KEY (id),
    CONSTRAINT fk_deals_conversations_conversation_id FOREIGN KEY (conversation_id) REFERENCES conversations (id) ON DELETE CASCADE,
    CONSTRAINT fk_deals_listings_listing_id FOREIGN KEY (listing_id) REFERENCES listings (id) ON DELETE CASCADE,
    CONSTRAINT fk_deals_users_buyer_id FOREIGN KEY (buyer_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_deals_users_seller_id FOREIGN KEY (seller_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE TABLE listing_images (
    id uuid NOT NULL,
    listing_id uuid NOT NULL,
    file_name text NOT NULL,
    position integer NOT NULL,
    CONSTRAINT pk_listing_images PRIMARY KEY (id),
    CONSTRAINT fk_listing_images_listings_listing_id FOREIGN KEY (listing_id) REFERENCES listings (id) ON DELETE CASCADE
);
CREATE TABLE listing_lines (
    id uuid NOT NULL,
    listing_id uuid NOT NULL,
    name text NOT NULL,
    quantity integer NOT NULL,
    position integer NOT NULL,
    CONSTRAINT pk_listing_lines PRIMARY KEY (id),
    CONSTRAINT fk_listing_lines_listings_listing_id FOREIGN KEY (listing_id) REFERENCES listings (id) ON DELETE CASCADE
);
CREATE TABLE reviews (
    id uuid NOT NULL,
    deal_id uuid NOT NULL,
    reviewer_id uuid,
    reviewee_id uuid NOT NULL,
    reviewer_role character varying(40) NOT NULL,
    stars integer NOT NULL,
    reason_tag character varying(40),
    comment text,
    created_at timestamp with time zone NOT NULL,
    published_at timestamp with time zone,
    reply text,
    replied_at timestamp with time zone,
    is_frozen boolean NOT NULL,
    is_removed boolean NOT NULL,
    CONSTRAINT pk_reviews PRIMARY KEY (id),
    CONSTRAINT ck_reviews_low_rating_context CHECK (stars > 2 OR (reason_tag IS NOT NULL AND comment IS NOT NULL AND length(trim(comment)) >= 20)),
    CONSTRAINT ck_reviews_stars CHECK (stars BETWEEN 1 AND 5),
    CONSTRAINT fk_reviews_deals_deal_id FOREIGN KEY (deal_id) REFERENCES deals (id) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_users_reviewee_id FOREIGN KEY (reviewee_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_users_reviewer_id FOREIGN KEY (reviewer_id) REFERENCES users (id) ON DELETE SET NULL
);
CREATE TABLE moderation_cases (
    id uuid NOT NULL,
    kind character varying(40) NOT NULL,
    review_id uuid,
    deal_id uuid NOT NULL,
    opened_by uuid NOT NULL,
    reason text NOT NULL,
    snapshot jsonb NOT NULL,
    status character varying(40) NOT NULL,
    resolution character varying(40),
    resolution_note text,
    resolved_by uuid,
    resolved_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_moderation_cases PRIMARY KEY (id),
    CONSTRAINT fk_moderation_cases_deals_deal_id FOREIGN KEY (deal_id) REFERENCES deals (id) ON DELETE CASCADE,
    CONSTRAINT fk_moderation_cases_reviews_review_id FOREIGN KEY (review_id) REFERENCES reviews (id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX ix_cities_external_id ON cities (external_id);
CREATE INDEX ix_conversation_participants_user_id ON conversation_participants (user_id);
CREATE INDEX ix_conversations_subject_type_subject_id ON conversations (subject_type, subject_id);
CREATE INDEX ix_deals_buyer_id ON deals (buyer_id);
CREATE INDEX ix_deals_conversation_id ON deals (conversation_id);
CREATE INDEX ix_deals_seller_id ON deals (seller_id);
CREATE UNIQUE INDEX ux_deals_one_open_per_listing ON deals (listing_id) WHERE status IN ('proposed','awaiting_handoff','awaiting_shipment','shipped','disputed');
CREATE INDEX ix_listing_images_listing_id ON listing_images (listing_id);
CREATE INDEX ix_listing_lines_listing_id ON listing_lines (listing_id);
CREATE INDEX ix_listings_city_id ON listings (city_id);
CREATE INDEX ix_listings_collection_type_id ON listings (collection_type_id);
CREATE INDEX ix_listings_owner_id ON listings (owner_id);
CREATE INDEX ix_listings_status_collection_type_id ON listings (status, collection_type_id);
CREATE INDEX ix_messages_conversation_id_created_at ON messages (conversation_id, created_at);
CREATE INDEX ix_messages_sender_id ON messages (sender_id);
CREATE INDEX ix_moderation_cases_deal_id ON moderation_cases (deal_id);
CREATE INDEX ix_moderation_cases_review_id ON moderation_cases (review_id);
CREATE INDEX ix_moderation_cases_status ON moderation_cases (status);
CREATE UNIQUE INDEX ix_reviews_deal_id_reviewer_id ON reviews (deal_id, reviewer_id);
CREATE INDEX ix_reviews_reviewee_id ON reviews (reviewee_id);
CREATE INDEX ix_reviews_reviewer_id ON reviews (reviewer_id);

-- Enum value guards (EF stores marketplace enums as snake_case text)
ALTER TABLE listings ADD CONSTRAINT ck_listings_kind CHECK (kind IN ('sell','exchange','wanted'));
ALTER TABLE listings ADD CONSTRAINT ck_listings_condition CHECK (condition IS NULL OR condition IN ('new','like_new','good','fair','poor'));
ALTER TABLE listings ADD CONSTRAINT ck_listings_status CHECK (status IN ('active','pending_pickup','pending_shipment','sold','archived'));
ALTER TABLE listings ADD CONSTRAINT ck_listings_price CHECK (price_cents IS NULL OR price_cents > 0);
ALTER TABLE listing_lines ADD CONSTRAINT ck_listing_lines_quantity CHECK (quantity BETWEEN 1 AND 9999);
ALTER TABLE conversation_participants ADD CONSTRAINT ck_participants_role CHECK (role IN ('owner','inquirer'));
ALTER TABLE messages ADD CONSTRAINT ck_messages_kind CHECK (kind IN ('text','price_offer','meetup_proposal','system'));
ALTER TABLE deals ADD CONSTRAINT ck_deals_method CHECK (method IN ('local_pickup','shipping'));
ALTER TABLE deals ADD CONSTRAINT ck_deals_status CHECK (status IN ('proposed','awaiting_handoff','awaiting_shipment','shipped','completed','disputed','cancelled'));
ALTER TABLE deals ADD CONSTRAINT ck_deals_completion_reason CHECK (completion_reason IS NULL OR completion_reason IN ('handoff_verified','receipt_confirmed','auto_completed','moderator'));
ALTER TABLE deals ADD CONSTRAINT ck_deals_parties CHECK (seller_id <> buyer_id);
ALTER TABLE reviews ADD CONSTRAINT ck_reviews_role CHECK (reviewer_role IN ('buyer','seller'));
ALTER TABLE reviews ADD CONSTRAINT ck_reviews_reason_tag CHECK (reason_tag IS NULL OR reason_tag IN ('item_not_as_described','late_to_meetup','no_show','poor_communication','damaged_in_shipping','slow_shipping','payment_problem','rude_behavior','other'));
ALTER TABLE moderation_cases ADD CONSTRAINT ck_moderation_kind CHECK (kind IN ('review_report','shipping_dispute'));
ALTER TABLE moderation_cases ADD CONSTRAINT ck_moderation_status CHECK (status IN ('open','resolved'));
ALTER TABLE moderation_cases ADD CONSTRAINT ck_moderation_resolution CHECK (resolution IS NULL OR resolution IN ('review_removed','review_restored','deal_completed','deal_cancelled'));

COMMIT;
