#!/usr/bin/env node
// Generates src/components/custom_ui/editor_fonts.ts: VendSans @font-face rules (base64) for the rich text editor's
// WebView, so edited text uses the same typeface as the rest of the app. Re-run after changing assets/fonts.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const face = (file, weight, style) =>
  `@font-face{font-family:'VendSans';src:url(data:font/ttf;base64,${readFileSync(join(root, "assets/fonts", file)).toString("base64")}) format('truetype');font-weight:${weight};font-style:${style};}`;
const css = [face("VendSans-Regular.ttf", 400, "normal"), face("VendSans-Bold.ttf", 700, "normal")].join("");
writeFileSync(
  join(root, "src/components/custom_ui/editor_fonts.ts"),
  `// GENERATED by scripts/gen-editor-fonts.mjs — do not edit.\nexport const EDITOR_FONT_FACES = ${JSON.stringify(css)};\n`,
);
console.log(`editor_fonts.ts written (${Math.round(css.length / 1024)} KB)`);
